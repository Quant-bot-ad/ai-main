def exact_if(ref, opts):
    """=IF(C10="a",10,IF(C10="b",0,"")) — точное сравнение по списку вариантов."""
    s = "".join(f'IF({ref}="{t}",{p},' for t, p in opts)
    return "=" + s + '""' + ")" * len(opts)


def add_dv(ws, sqref, formula1):
    dv = DataValidation(type="list", formula1=formula1, allow_blank=True,
                        showDropDown=False, showErrorMessage=True, showInputMessage=True)
    dv.add(sqref)
    ws.add_data_validation(dv)


