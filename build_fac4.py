def build_rating(name, subtitle, rows, widths, top10=False):
    """rows: list of (должность, звание, ФИО, имя_листа, ячейка_суммы)"""
    ws = wb.create_sheet(name)
    for col, w in widths.items():
        ws.column_dimensions[col].width = w
    for r, h in {1: 15.75, 2: 18.75, 3: 18.75, 4: 18.75, 5: 18.75, 7: 16.5,
                 8: 18.75, 9: 19.5}.items():
        ws.row_dimensions[r].height = h
    # титульный блок
    titles = ["", "СВОДНАЯ ВЕДОМОСТЬ", "определения рейтинговой оценки служебной",
              subtitle, "факультета №4", "(подразделение)"]
    for i, t in enumerate(titles, start=1):
        ws.merge_cells(f"A{i}:F{i}")
        c = ws[f"A{i}"]
        c.value = t if t else None
        c.font = TNR14B
        c.alignment = CTR
    # шапка таблицы (A8='№', A9='п/п' — не объединяются; B..F объединены по вертикали)
    heads = [None, "Должность", "Воинское звание", "Фамилия, имя, отчество",
             "Количество баллов", "Общее место"]
    for ci, h in enumerate(heads, start=1):
        if h is not None:
            ws.merge_cells(start_row=8, start_column=ci, end_row=9, end_column=ci)
            ws.cell(row=8, column=ci).value = h
    ws["A8"] = "№"
    ws["A9"] = "п/п"
    for r in (8, 9):
        for ci in range(1, 7):
            c = ws.cell(row=r, column=ci)
            c.font = TNR14B
            c.alignment = CTR
            c.border = BOX
    # данные
    first, n = 10, len(rows)
    last = first + n - 1
    for i, (dolzh, rank, fio, sheet, sumcell) in enumerate(rows):
        r = first + i
        ws.row_dimensions[r].height = 38.25
        parts = fio.split(" ", 1)
        fio_nl = f"{parts[0]} \n{parts[1]}" if len(parts) > 1 else fio
        vals = [i + 1, dolzh, rank, fio_nl, f"='{sheet}'!{sumcell}",
                f"=_xlfn.RANK.EQ(E{r},$E${first}:$E${last}, 0)"]
        for ci, v in enumerate(vals, start=1):
            c = ws.cell(row=r, column=ci)
            c.value = v
            c.font = TNR14
            c.alignment = CTR
            c.border = BOX
    # подпись
    sig = last + 1
    for k, text in enumerate(["Начальник факультета №4",
                              "полковник                              Д.Калинин",
                              '"    " октября 2026 г.']):
        r = sig + k
        ws.merge_cells(f"A{r}:F{r}")
        ws.row_dimensions[r].height = 18.75
        c = ws[f"A{r}"]
        c.value = text
        c.font = TNR14B
        c.alignment = Alignment(horizontal="center")
        if k == 0:
            for ci in range(1, 7):
                ws.cell(row=r, column=ci).border = Border(top=MED)
    if top10:
        rule = Rule(type="top10", dxf=DifferentialStyle(fill=PatternFill(bgColor="FFFF0000")), rank=10)
        ws.conditional_formatting.add(f"A8:F{last}", rule)
    new_order.append(ws)
    return ws

